"""
LLM-facing output schemas for Aegis agents.

These models define strictly what the LLM generates:
- No runtime execution state (status, output, retry_count, task_id, timestamps)
- No typeless Any fields
- No datetime fields
- No aliases

Runtime models (ExecutionPlan, SubTask, ToolCallRecord) live in aegis.models.schemas.
"""
from __future__ import annotations

from enum import Enum
from typing import List, Literal, Tuple, Type

from pydantic import BaseModel, Field


class AgentRole(str, Enum):
    PLANNER = "planner"
    RESEARCH = "research"
    DATA_ANALYST = "data_analyst"
    CODING = "coding"
    VERIFICATION = "verification"
    CRITIC = "critic"
    SYNTHESIZER = "synthesizer"


class PlannedSubtask(BaseModel):
    """Subtask specification generated by PlannerAgent."""

    id: str
    description: str
    role: AgentRole = AgentRole.RESEARCH
    tools: List[str] = Field(default_factory=list)
    depends_on: List[str] = Field(default_factory=list)


class PlanOutput(BaseModel):
    """Decomposition plan produced by PlannerAgent."""

    objective: str
    rationale: str = ""
    subtasks: List[PlannedSubtask] = Field(default_factory=list)


class EvidenceRef(BaseModel):
    """Citation reference to tool call, retrieval chunk, or tool output."""

    kind: Literal["tool_call", "chunk", "tool_output"]
    ref_id: str


class Finding(BaseModel):
    """Specific empirical or factual claim backed by evidence."""

    statement: str
    evidence: List[EvidenceRef] = Field(default_factory=list)


class SpecialistOutput(BaseModel):
    """Output generated by research or data_analyst specialist agents."""

    summary: str
    findings: List[Finding] = Field(default_factory=list)
    limitations: List[str] = Field(default_factory=list)


class JudgeVerdict(BaseModel):
    """Audit verdict produced by LLM judge for claim verification."""

    verdict: Literal["supported", "contradicted", "not_enough_info"]
    quote_span: str = Field(default="", description="Exact verbatim substring quoted from the evidence text.")
    rationale: str = Field(default="", description="Explanation of verification verdict.")


class CriticRubricOutput(BaseModel):
    """Evaluation scores and feedback produced by CriticAgent."""

    answers_question: float = Field(ge=0.0, le=10.0, description="Score 0-10 for addressing the engineering question.")
    uses_task_data: float = Field(ge=0.0, le=10.0, description="Score 0-10 for utilizing task data and evidence.")
    claims_verified: float = Field(ge=0.0, le=10.0, description="Score 0-10 for factual consistency and verification.")
    limitations_stated: float = Field(ge=0.0, le=10.0, description="Score 0-10 for documenting limitations.")
    retry_subtask_ids: List[str] = Field(default_factory=list, description="IDs of subtasks requiring targeted retry.")
    replan: bool = Field(default=False, description="Whether the plan decomposition is fundamentally flawed.")
    guidance: str = Field(default="", description="Concrete guidance for retry or replan.")
    issues_found: List[str] = Field(default_factory=list, description="List of flaws or gaps identified.")


class SynthesizerOutput(BaseModel):
    """Draft synthesis report produced by SynthesizerAgent."""

    title: str
    final_finding: str
    key_conclusions: List[str] = Field(default_factory=list)
    actionable_recommendations: List[str] = Field(default_factory=list)
    evidence_summary: str = ""
    data_analysis_summary: str = ""
    recommended_action: str = ""
    urgency: str = "medium"
    operational_steps: List[str] = Field(default_factory=list)


ALL_LLM_OUTPUT_SCHEMAS: Tuple[Type[BaseModel], ...] = (
    PlanOutput,
    SpecialistOutput,
    JudgeVerdict,
    CriticRubricOutput,
    SynthesizerOutput,
)
